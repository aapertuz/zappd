def _node(
    node_id: str,
    parent_id: str | None,
    name: str,
    level: str,
    depth: int,
    category: str,
    color_hex: str,
    dimensions_mm: list[float],
    rest_position_m: list[float],
    explode_dir: list[float],
    explode_dist_m: float,
    material_hint: str,
    spdx_license: str,
    source_url: str,
    source_name: str,
    step_fixture_name: str | None,
    specifications: dict[str, Any],
    expected_step_sha256: str | None = None,
) -> dict[str, Any]:
    spec: dict[str, Any] = {
        "id": node_id,
        "parentId": parent_id,
        "name": name,
        "level": level,
        "depth": depth,
        "category": category,
        "colorHex": color_hex,
        "dimensionsMm": dimensions_mm,
        "restPositionMeters": rest_position_m,
        "explodeDirection": explode_dir,
        "explodeDistanceMeters": explode_dist_m,
        "materialHint": material_hint,
        "origin": "open_step_catalog",
        "spdxLicense": spdx_license,
        "sourceUrl": source_url,
        "sourceName": source_name,
        "stepFixtureName": step_fixture_name,
        "specifications": specifications,
    }
    if expected_step_sha256 is not None:
        spec["expectedStepSha256"] = expected_step_sha256
    return spec


