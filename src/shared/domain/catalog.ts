import type {
  AssemblyInstructionStep,
  AssemblyStepId,
  CatalogArchetypeId,
  ComponentId,
  ComponentRelationship,
  GeometryOrigin,
  HierarchyLevel,
  RelationshipConnectionType,
  RelationshipId,
  Vector3Tuple,
} from './assembly';

export type CatalogComponentBlueprint = {
  readonly id: ComponentId;
  readonly parentId: ComponentId | null;
  readonly name: string;
  readonly level: HierarchyLevel;
  readonly depth: number;
  readonly category: string;
  readonly colorHex: string;
  readonly dimensionsMm: Vector3Tuple;
  readonly restPositionMeters: Vector3Tuple;
  readonly explodeDirection: Vector3Tuple;
  readonly explodeDistanceMeters: number;
  readonly materialHint: string;
  readonly origin: GeometryOrigin;
  readonly spdxLicense: string;
  readonly sourceUrl: string;
  readonly sourceName: string;
  readonly stepFixtureName: string | null;
  readonly specifications: Readonly<Record<string, string | number | boolean>>;
};

export type CatalogArchetypeDefinition = {
  readonly archetypeId: CatalogArchetypeId;
  readonly title: string;
  readonly summary: string;
  readonly keywords: readonly string[];
  readonly rootNodeId: ComponentId;
  readonly nodes: readonly CatalogComponentBlueprint[];
  readonly relationships: readonly ComponentRelationship[];
  readonly assemblySteps: readonly AssemblyInstructionStep[];
};

const cid = (value: string): ComponentId => {
  return value as ComponentId;
};

const rid = (value: string): RelationshipId => {
  return value as RelationshipId;
};

const sid = (value: string): AssemblyStepId => {
  return value as AssemblyStepId;
};

const aid = (value: string): CatalogArchetypeId => {
  return value as CatalogArchetypeId;
};

