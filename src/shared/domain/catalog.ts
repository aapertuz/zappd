function makeNode(
  id: string,
  parentId: string | null,
  name: string,
  level: HierarchyLevel,
  depth: number,
  category: string,
  colorHex: string,
  dimensionsMm: Vector3Tuple,
  restPositionMeters: Vector3Tuple,
  explodeDirection: Vector3Tuple,
  explodeDistanceMeters: number,
  materialHint: string,
  spdxLicense: string,
  sourceUrl: string,
  sourceName: string,
  stepFixtureName: string | null,
  specifications: Readonly<Record<string, string | number | boolean>>,
): CatalogComponentBlueprint {
  return {
    id: cid(id),
    parentId: parentId === null ? null : cid(parentId),
    name,
    level,
    depth,
    category,
    colorHex,
    dimensionsMm,
    restPositionMeters,
    explodeDirection,
    explodeDistanceMeters,
    materialHint,
    origin: 'open_step_catalog',
    spdxLicense,
    sourceUrl,
    sourceName,
    stepFixtureName,
    specifications,
  };
}

function makeConnection(
  id: string,
  from: string,
  to: string,
  connectionType: RelationshipConnectionType,
  howConnected: string,
  whyConnected: string,
): ComponentRelationship {
  return {
    id: rid(id),
    fromComponentId: cid(from),
    toComponentId: cid(to),
    connectionType,
    howConnected,
    whyConnected,
  };
}

function makeStep(
  id: string,
  order: number,
  title: string,
  summary: string,
  componentIds: readonly string[],
  relationshipIds: readonly string[],
): AssemblyInstructionStep {
  return {
    id: sid(id),
    order,
    title,
    summary,
    componentIds: componentIds.map(cid),
    relationshipIds: relationshipIds.map(rid),
  };
}

